export function getActiveAlerts() {
  return devices.flatMap((device) =>
    device.alerts
      .filter((alert) => alert.severity === "critical" && device.status !== "active")
      .map((alert) => ({ device, alert })),
  );
}

export function exportFleetCsv() {
  const header = [
    "id",
    "name",
    "city",
    "state",
    "language",
    "keyword",
    "status",
    "activations_24h",
    "tpr_percent",
    "far_percent",
    "avg_latency_ms",
    "uptime_percent",
    "battery_percent",
  ];
  const rows = devices.map((d) =>
    [
      d.id,
      d.name,
      d.city,
      d.state,
      d.language,
      d.keyword,
      d.status,
      d.activations24h,
      d.tprPercent,
      d.farPercent,
      d.avgLatencyMs || d.lastLatencyMs,
      d.uptimePercent,
      d.batteryPercent,
    ].join(","),
  );
  return [header.join(","), ...rows].join("\n");
}
